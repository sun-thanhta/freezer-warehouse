#!/usr/bin/env node
// Writes .env.local from the RUNNING local Supabase stack (`supabase status -o env`).
// Local keys are per-machine dev keys, never production secrets — still gitignored.
// Usage: npm run db:start && npm run env:local

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

let raw;
try {
  raw = execFileSync("npx", ["supabase", "status", "-o", "env"], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
} catch (err) {
  console.error("✖ Supabase local chưa chạy. Bật Docker (colima start) rồi `npm run db:start`.\n", err.stderr?.toString() ?? "");
  process.exit(1);
}

const env = Object.fromEntries(
  raw.split("\n").map((l) => l.match(/^([A-Z0-9_]+)="?(.*?)"?$/)).filter(Boolean).map((m) => [m[1], m[2]]),
);
const pick = (...keys) => keys.map((k) => env[k]).find(Boolean);
const values = {
  NEXT_PUBLIC_SUPABASE_URL: pick("API_URL"),
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: pick("PUBLISHABLE_KEY", "ANON_KEY"),
  SUPABASE_SECRET_KEY: pick("SECRET_KEY", "SERVICE_ROLE_KEY"),
  SUPABASE_DB_URL: pick("DB_URL"),
};
const missing = Object.entries(values).filter(([, v]) => !v).map(([k]) => k);
if (missing.length) {
  console.error(`✖ Không đọc được từ supabase status: ${missing.join(", ")}`);
  process.exit(1);
}

const body = [
  "# Generated by `npm run env:local` from the local Supabase stack. Do not commit.",
  "# SUPABASE_SECRET_KEY / SUPABASE_DB_URL are for dev scripts only — never prefix them with NEXT_PUBLIC_.",
  ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
  "",
].join("\n");
writeFileSync(".env.local", body);
console.log(`✔ Đã ghi .env.local (${Object.keys(values).join(", ")})`);
